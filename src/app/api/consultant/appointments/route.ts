import { NextResponse } from 'next/server';
import { getServerSession } from 'next-auth/next';
import { authOptions } from '@/lib/auth';
import { db } from '@/lib/db';
import { createMeetEvent } from '@/lib/google-calendar';

export async function GET(req: Request) {
  try {
    const session = await getServerSession(authOptions);
    if (!session || (session.user as any).role !== 'CONSULTANT') {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }
    const profile = await db.consultantProfile.findUnique({ where: { userId: Number((session.user as any).id) } });
    if (!profile) return NextResponse.json({ error: 'Profile not found' }, { status: 404 });

    const { searchParams } = new URL(req.url);
    const status = searchParams.get('status') || '';
    const where: any = { consultantId: profile.id };
    if (status) where.status = status;

    const appointments = await db.appointment.findMany({
      where,
      orderBy: { scheduledAt: 'desc' },
      include: { user: { select: { id: true, name: true, email: true, avatar: true } } },
    });
    return NextResponse.json(appointments);
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}

export async function PATCH(req: Request) {
  try {
    const session = await getServerSession(authOptions);
    if (!session || (session.user as any).role !== 'CONSULTANT') {
      return NextResponse.json({ error: 'Unauthorized' }, { status: 401 });
    }
    const profile = await db.consultantProfile.findUnique({
      where: { userId: Number((session.user as any).id) },
      include: { user: { select: { name: true, email: true } } },
    });
    if (!profile) return NextResponse.json({ error: 'Profile not found' }, { status: 404 });

    const { id, status, meetingLink, notes } = await req.json();
    const appt = await db.appointment.findFirst({
      where: { id: Number(id), consultantId: profile.id },
      include: { user: { select: { name: true, email: true } } },
    });
    if (!appt) return NextResponse.json({ error: 'Not found' }, { status: 404 });

    // Auto-generate Google Meet for VIDEO appointments in two scenarios:
    // 1. When confirming (status === 'CONFIRMED') with no link yet
    // 2. When the doctor manually clicks "Auto-Generate" (no status, no meetingLink override)
    let autoMeetLink: string | undefined;
    let meetError: string | undefined;

    const isVideoAppt = appt.type === 'VIDEO';
    const noManualLink = meetingLink === undefined || meetingLink === null || meetingLink === '';
    const hasGoogleCreds =
      process.env.GOOGLE_CLIENT_ID &&
      process.env.GOOGLE_CLIENT_SECRET &&
      process.env.GOOGLE_REFRESH_TOKEN;

    const shouldGenerate =
      isVideoAppt &&
      noManualLink &&
      (status === 'CONFIRMED' || !status); // fires on confirm OR manual generate button

    if (shouldGenerate) {
      if (!hasGoogleCreds) {
        meetError = 'Google credentials missing in .env.local (GOOGLE_CLIENT_ID / GOOGLE_CLIENT_SECRET / GOOGLE_REFRESH_TOKEN)';
        console.error('[Google Meet]', meetError);
      } else {
        try {
          const result = await createMeetEvent({
            appointmentId: appt.id,
            doctorName: profile.user.name,
            doctorEmail: profile.user.email,
            patientName: appt.patientName || appt.user.name,
            patientEmail: appt.user.email,
            scheduledAt: appt.scheduledAt,
            durationMinutes: appt.duration,
            concern: appt.concern,
          });
          autoMeetLink = result.meetLink;
        } catch (err: any) {
          meetError = err.message || 'Unknown error from Google Calendar API';
          console.error('[Google Meet] Failed to create Meet link:', meetError);
        }
      }
    }

    const updated = await db.appointment.update({
      where: { id: Number(id) },
      data: {
        ...(status && { status }),
        // Priority: manual override > auto-generated > keep existing
        ...((meetingLink !== undefined || autoMeetLink) && {
          meetingLink: meetingLink !== undefined ? meetingLink : autoMeetLink,
        }),
        ...(notes !== undefined && { notes }),
      },
      include: { user: { select: { id: true, name: true, email: true, avatar: true } } },
    });
    return NextResponse.json({ ...updated, meetAutoGenerated: !!autoMeetLink, meetError });
  } catch (err: any) {
    return NextResponse.json({ error: err.message }, { status: 500 });
  }
}
